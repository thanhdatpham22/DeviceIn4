"""Generate Android resources and the migration adapter from the reviewed catalog."""
from pathlib import Path
import json, re, hashlib
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
entries = json.loads((ROOT/'tools/localization_catalog.json').read_text(encoding='utf-8'))
vi_labels = json.loads((ROOT/'tools/localization_vi_labels.json').read_text(encoding='utf-8'))
translated = {}
for line in (ROOT/'tools/localization_translations.tsv').read_text(encoding='utf-8').splitlines():
    if not line or line.startswith('#'): continue
    index, fr, ja, zh = line.split('|')
    translated[int(index)] = dict(fr=fr, ja=ja, zh=zh)
assert len(translated) == len(entries), (len(translated), len(entries))
for line in (ROOT/'tools/localization_extra.tsv').read_text(encoding='utf-8').splitlines():
    if not line or line.startswith('#'): continue
    vi, en, fr, ja, zh = line.split('|')
    if any(entry['vi'] == vi for entry in entries): continue
    slug = re.sub('[^a-z0-9]+', '_', en.lower()).strip('_')[:55]
    translated[len(entries)] = dict(fr=fr, ja=ja, zh=zh)
    args = max([int(n) for n in re.findall(r'%(\d+)\$s', vi)] or [0])
    entries.append(dict(name='ui_' + slug + '_' + hashlib.sha1(vi.encode()).hexdigest()[:6], vi=vi, en=en, args=args))

def xml_text(text, args=0):
    if args: text = re.sub(r'%(?!\d+\$[sd])', '%%', text)
    return escape(text).replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')

extra = {
    'en': ('%1$sd %2$sh %3$sm', 'CPU running and jumping on grass', '%d app', '%d apps'),
    'vi': ('%1$s ngày %2$s giờ %3$s phút', 'CPU chạy nhảy trên nền cỏ', '%d ứng dụng', '%d ứng dụng'),
    'fr': ('%1$s j %2$s h %3$s min', 'Un CPU court et saute dans l’herbe', '%d application', '%d applications'),
    'ja': ('%1$s日 %2$s時間 %3$s分', '草原を走ってジャンプするCPU', '%d件のアプリ', '%d件のアプリ'),
    'zh': ('%1$s天 %2$s小时 %3$s分钟', '在草地上奔跑跳跃的 CPU', '%d 个应用', '%d 个应用'),
}
for locale, folder in [('en','values'), ('vi','values-vi'), ('fr','values-fr'), ('ja','values-ja'), ('zh','values-b+zh+Hans')]:
    destination = ROOT/'app/src/main/res'/folder
    destination.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>', '    <string name="app_name" translatable="false">Device Info</string>']
    for index, entry in enumerate(entries):
        value = entry[locale] if locale in ('en','vi') else translated[index][locale]
        if locale == 'vi': value = vi_labels.get(entry['vi'], value)
        assert sorted(re.findall(r'%\d+\$s', value)) == sorted(re.findall(r'%\d+\$s', entry['en'])), (locale, index)
        attr = '' if entry['args'] else ' formatted="false"'
        lines.append(f'    <string name="{entry["name"]}"{attr}>{xml_text(value, entry["args"])}</string>')
    duration, scene, singular, plural = extra[locale]
    duration = duration.replace('$s', '$d')
    panel = {
        'en': 'Display name: %1$s · OEM PNP code: %2$s',
        'vi': 'Tên màn hình: %1$s · Mã OEM PNP: %2$s',
        'fr': 'Nom de la dalle : %1$s · Code PNP OEM : %2$s',
        'ja': 'パネル名：%1$s・OEM PNPコード：%2$s',
        'zh': '屏幕名称：%1$s · OEM PNP 代码：%2$s',
    }[locale]
    lines += [f'    <string name="duration_format">{xml_text(duration, 3)}</string>',
              f'    <string name="panel_oem_format">{xml_text(panel, 2)}</string>',
              f'    <string name="cpu_play_description">{xml_text(scene)}</string>',
              '    <plurals name="visible_app_count">',
              f'        <item quantity="one">{xml_text(singular)}</item>',
              f'        <item quantity="other">{xml_text(plural)}</item>', '    </plurals>', '</resources>']
    (destination/'strings.xml').write_text('\n'.join(lines)+'\n', encoding='utf-8')

def kt(text): return json.dumps(text, ensure_ascii=False).replace('$', '\\$')
aliases, templates = {}, []
for entry in entries:
    for lang in ('vi','en'):
        value = entry[lang]
        if entry['args']:
            if len(re.sub(r'%\d+\$s', '', value).strip()) >= 4:
                templates.append((value, entry['name']))
        else: aliases.setdefault(value, entry['name'])
    if entry['vi'] in vi_labels: aliases.setdefault(vi_labels[entry['vi']], entry['name'])
for alias, source in {'Sensor': 'Cảm biến', 'Device Information': 'Thông tin thiết bị'}.items():
    aliases.setdefault(alias, aliases[source])
code = ['package com.devicein4.app', '', '// Generated by tools/emit_locales.py; translations live in res/values*/strings.xml.',
        'internal object LegacyStringResources {', '    val aliases: Map<String, Int> = mapOf(']
code += [f'        {kt(alias)} to R.string.{name},' for alias,name in aliases.items()]
code += ['    )', '    val templates: List<Pair<String, Int>> = listOf(']
code += [f'        {kt(value)} to R.string.{name},' for value,name in templates]
code += ['    )', '}']
(ROOT/'app/src/main/java/com/devicein4/app/LegacyStringResources.kt').write_text('\n'.join(code)+'\n', encoding='utf-8')
print(f'Wrote {len(entries)} reviewed messages in five languages, {len(aliases)} aliases and {len(templates)} templates.')
